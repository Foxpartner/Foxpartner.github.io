# Converts catalogo.csv into data/catalog.js (used by the website).
# Run from the project folder:  powershell -ExecutionPolicy Bypass -File tools\build-data.ps1
param([string]$Csv = '')
$root = Split-Path -Parent $PSScriptRoot
$csv = $Csv; if (-not $csv) { $csv = Join-Path $root 'catalogo.csv' }
$out = Join-Path $root 'data\catalog.js'
$thumbs = Join-Path $root 'assets\thumbs'

$rows = Import-Csv $csv -Encoding UTF8 | ForEach-Object {
  $row = [ordered]@{ a = $_.artist; g = $_.group; f = $_.featuring; r = $_.reacted; t = $_.type; p = $_.platform; d = $_.date; u = $_.url; o = $_.original_title }
  # free Patreon posts: thumbnail saved by update-catalog.ps1 as assets/thumbs/patreon-<post id>.jpg
  if ($_.platform -eq 'Patreon' -and $_.url -match '-(\d+)$') {
    $name = 'patreon-' + $Matches[1] + '.jpg'
    if (Test-Path (Join-Path $thumbs $name)) { $row.i = 'assets/thumbs/' + $name }
  }
  $row
}
$json = ConvertTo-Json @($rows) -Compress -Depth 3
$body = "window.FOX_CATALOG = $json;"
if ((Test-Path $out) -and ([IO.File]::ReadAllText($out).Contains($body))) { "No changes in $out ($(@($rows).Count) items)"; return }
$stamp = (Get-Date).ToString('yyyy-MM-dd')
$js = "// Generated by tools/build-data.ps1 on $stamp - do not edit by hand, edit catalogo.csv instead.`n$body`n"

New-Item -ItemType Directory -Force (Split-Path $out) | Out-Null
[IO.File]::WriteAllText($out, $js, (New-Object System.Text.UTF8Encoding($false)))
"Wrote $(@($rows).Count) items to $out"
